if USE_PG:
    import psycopg
    from psycopg_pool import ConnectionPool

    IntegrityError = (sqlite3.IntegrityError, psycopg.IntegrityError)

    class _Row(dict):
        """PostgreSQL 的行:和 sqlite3.Row 一样,row["name"] 和 row[0] 都能用。"""
        __slots__ = ("_v",)

        def __init__(self, names, values):
            super().__init__(zip(names, values))
            self._v = values

        def __getitem__(self, k):
            return self._v[k] if isinstance(k, int) else dict.__getitem__(self, k)

    def _row_factory(cursor):
        names = [d.name for d in cursor.description or ()]
        return lambda values: _Row(names, values)

    # 取用连接前先检查(Neon 等托管库休眠时会断开连接);闲置 2 分钟的连接全部关掉,
    # 不常驻连接,让免费数据库能尽快休眠、少用免费额度
    _pool = ConnectionPool(DATABASE_URL, min_size=0, max_size=8, max_idle=120, timeout=30,
                           check=ConnectionPool.check_connection, open=True,
                           kwargs={"row_factory": _row_factory, "prepare_threshold": None})
    atexit.register(_pool.close)
else:
    IntegrityError = sqlite3.IntegrityError


class _Conn:
    def __init__(self, raw):
        self.raw = raw

    def execute(self, sql, args=()):
        if USE_PG:
            sql = sql.replace("%", "%%").replace("?", "%s")
        return self.raw.execute(sql, tuple(args))

    def insert(self, sql, args):
        """执行 INSERT 并返回新行的 id。"""
        if USE_PG:
            return self.execute(sql + " RETURNING id", args).fetchone()[0]
        return self.execute(sql, args).lastrowid


def _init_db():
    if USE_PG:
        with _pool.connection() as raw:
            for stmt in SCHEMA_PG.split(";"):
                if stmt.strip():
                    raw.execute(stmt)
        return
    os.makedirs(os.path.dirname(DB_PATH) or ".", exist_ok=True)
    with sqlite3.connect(DB_PATH) as c:
        c.execute("PRAGMA journal_mode=WAL")
        c.executescript(SCHEMA_SQLITE)


@contextmanager
def db():
    """一次请求用一个事务:正常结束提交,抛异常(包括 HTTPException)回滚。"""
    if USE_PG:
        with _pool.connection() as raw:      # 退出时自动提交 / 回滚并放回连接池
            yield _Conn(raw)
        return
    c = sqlite3.connect(DB_PATH, timeout=10)
    c.row_factory = sqlite3.Row
    c.execute("PRAGMA foreign_keys=ON")
    try:
        yield _Conn(c)
        c.commit()
    finally:
        c.close()


def _on_mount(path):
    p = os.path.dirname(os.path.abspath(path))
    while p and p != os.path.dirname(p):
        if os.path.ismount(p):
            return True
        p = os.path.dirname(p)
    return False


def storage_info():
    """数据存在哪、会不会丢。Render 上只有挂载的持久磁盘里的文件能在重启/重新部署后保留。"""
    if USE_PG:
        return {"storage": "postgres", "persistent": True}
    persistent = _on_mount(DB_PATH) if os.environ.get("RENDER") else None
    return {"storage": "sqlite", "persistent": persistent}


