def _hash_pw(password, salt):
    return hashlib.scrypt(password.encode("utf-8"), salt=salt, n=2 ** 14, r=8, p=1, dklen=32)


def _token_hash(tok):
    return hashlib.sha256(tok.encode("ascii")).hexdigest()


class Limiter:
    """简单的内存限流:同一个 key 在 window 秒内最多 n 次。"""

    def __init__(self):
        self.hits = defaultdict(deque)
        self.lock = threading.Lock()

    def check(self, key, n, window, record=True):
        now = time.time()
        with self.lock:
            q = self.hits[key]
            while q and q[0] < now - window:
                q.popleft()
            if len(q) >= n:
                return False
            if record:
                q.append(now)
            return True

    def add(self, key):
        with self.lock:
            self.hits[key].append(time.time())


limiter = Limiter()


def client_ip(request: Request):
    if TRUST_PROXY:
        xff = request.headers.get("x-forwarded-for", "")
        if xff:
            return xff.split(",")[0].strip()
    return request.client.host if request.client else "?"


def public_user(row):
    return {"id": row["id"], "name": row["name"], "email": row["email"],
            "admin": row["email"].lower() in ADMIN_EMAILS}


def _new_session(c, user_id):
    tok = secrets.token_urlsafe(32)
    now = time.time()
    c.execute("INSERT INTO sessions(token_hash, user_id, created, expires) VALUES(?,?,?,?)",
              (_token_hash(tok), user_id, now, now + SESSION_DAYS * 86400))
    c.execute("DELETE FROM sessions WHERE expires < ?", (now,))
    return tok


def _user_from_auth(authorization):
    if not authorization or not authorization.startswith("Bearer "):
        return None
    with db() as c:
        return c.execute("""SELECT users.* FROM sessions JOIN users ON users.id = sessions.user_id
                            WHERE token_hash=? AND expires>?""",
                         (_token_hash(authorization[7:].strip()), time.time())).fetchone()


def optional_user(authorization: Optional[str] = Header(default=None)):
    return _user_from_auth(authorization)


def current_user(authorization: Optional[str] = Header(default=None)):
    u = _user_from_auth(authorization)
    if u is None:
        raise HTTPException(401, "请先登录")
    return u


