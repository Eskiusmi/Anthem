class KitIn(BaseModel):
    title: str = Field(min_length=1, max_length=40)
    description: str = Field(default="", max_length=500)
    tags: list[str] = Field(default_factory=list, max_length=5)
    songs: list[SongIn] = Field(min_length=1, max_length=30)
    events: dict[str, EventIn] = Field(min_length=1)


def _validate_kit(kit: KitIn):
    ids = [s.id for s in kit.songs]
    if len(set(ids)) != len(ids):
        raise HTTPException(400, "歌曲编号重复")
    for k, e in kit.events.items():
        if k not in EVENT_KEYS:
            raise HTTPException(400, f"未知的站点:{k}")
        if e.song not in ids:
            raise HTTPException(400, f"站点 {k} 引用了不存在的歌曲 {e.song}")
    tags = []
    for t in kit.tags:
        t = t.strip()
        if t and len(t) <= 12 and t not in tags:
            tags.append(t)
    data = {
        "songs": [{"id": s.id, "title": s.title.strip(), "artist": s.artist.strip(), "duration": round(s.duration, 2),
                   "fp": [round(min(1.0, max(0.0, v)), 3) for v in s.fp] if s.fp else None,
                   "fp_rate": s.fp_rate} for s in kit.songs],
        "events": {k: e.model_dump() for k, e in kit.events.items()},
    }
    search = " ".join([kit.title, kit.description] + tags + [f"{s.title} {s.artist}" for s in kit.songs]).lower()
    return tags, data, search


def _summary(row, user=None, liked=False):
    data = json.loads(row["data"])
    return {
        "id": row["id"], "title": row["title"], "description": row["description"],
        "tags": json.loads(row["tags"]), "author": row["author"],
        "songs": [{"title": s["title"], "artist": s["artist"]} for s in data["songs"]],
        "stations": sorted(k for k, e in data["events"].items() if e.get("enabled", True)),
        "likes": row["likes"], "downloads": row["downloads"],
        "created": row["created"], "updated": row["updated"],
        "mine": bool(user and user["id"] == row["user_id"]), "liked": liked,
    }


KIT_SELECT = "SELECT kits.*, users.name AS author FROM kits JOIN users ON users.id = kits.user_id"


@app.get("/api/kits")
def list_kits(sort: str = "new", q: str = "", page: int = 1, mine: bool = False, user=Depends(optional_user)):
    page = max(1, min(page, 500))
    where, args = [], []
    if q.strip():
        for word in q.lower().split()[:5]:
            word = word.replace("\\", "\\\\").replace("%", "\\%").replace("_", "\\_")
            where.append("(kits.search LIKE ? ESCAPE '\\' OR lower(users.name) LIKE ? ESCAPE '\\')")
            args += [f"%{word}%", f"%{word}%"]
    if mine:
        if not user:
            raise HTTPException(401, "请先登录")
        where.append("kits.user_id=?")
        args.append(user["id"])
    order = "(kits.likes * 3 + kits.downloads) DESC, kits.created DESC" if sort == "popular" else "kits.created DESC"
    sql = KIT_SELECT + (" WHERE " + " AND ".join(where) if where else "") + f" ORDER BY {order} LIMIT ? OFFSET ?"
    with db() as c:
        rows = c.execute(sql, args + [PAGE_SIZE + 1, (page - 1) * PAGE_SIZE]).fetchall()
        liked = set()
        if user and rows:
            ids = [r["id"] for r in rows]
            liked = {r[0] for r in c.execute(f"SELECT kit_id FROM likes WHERE user_id=? AND kit_id IN ({','.join('?' * len(ids))})",
                                             [user["id"]] + ids)}
    return {"kits": [_summary(r, user, r["id"] in liked) for r in rows[:PAGE_SIZE]],
            "page": page, "has_more": len(rows) > PAGE_SIZE}


def _get_kit_row(c, kit_id):
    row = c.execute(KIT_SELECT + " WHERE kits.id=?", (kit_id,)).fetchone()
    if row is None:
        raise HTTPException(404, "这个音乐盒不存在或已被删除")
    return row


@app.get("/api/kits/{kit_id}")
def get_kit(kit_id: int, user=Depends(optional_user)):
    with db() as c:
        row = _get_kit_row(c, kit_id)
        liked = bool(user and c.execute("SELECT 1 FROM likes WHERE user_id=? AND kit_id=?", (user["id"], kit_id)).fetchone())
    out = _summary(row, user, liked)
    out["data"] = json.loads(row["data"])
    return out


@app.post("/api/kits")
def create_kit(kit: KitIn, user=Depends(current_user)):
    if not limiter.check(f"pub:{user['id']}", 30, 86400):
        raise HTTPException(429, "今天发布太多次了,明天再来")
    tags, data, search = _validate_kit(kit)
    now = time.time()
    with db() as c:
        kid = c.insert("""INSERT INTO kits(user_id, title, description, tags, data, search, created, updated)
                          VALUES(?,?,?,?,?,?,?,?)""",
                       (user["id"], kit.title.strip(), kit.description.strip(), json.dumps(tags, ensure_ascii=False),
                        json.dumps(data, ensure_ascii=False), search, now, now))
        row = _get_kit_row(c, kid)
    return _summary(row, user)


@app.put("/api/kits/{kit_id}")
def update_kit(kit_id: int, kit: KitIn, user=Depends(current_user)):
    tags, data, search = _validate_kit(kit)
    with db() as c:
        row = _get_kit_row(c, kit_id)
        if row["user_id"] != user["id"]:
            raise HTTPException(403, "只能修改自己的音乐盒")
        c.execute("UPDATE kits SET title=?, description=?, tags=?, data=?, search=?, updated=? WHERE id=?",
                  (kit.title.strip(), kit.description.strip(), json.dumps(tags, ensure_ascii=False),
                   json.dumps(data, ensure_ascii=False), search, time.time(), kit_id))
        row = _get_kit_row(c, kit_id)
    return _summary(row, user)


@app.delete("/api/kits/{kit_id}")
def delete_kit(kit_id: int, user=Depends(current_user)):
    with db() as c:
        row = _get_kit_row(c, kit_id)
        if row["user_id"] != user["id"] and user["email"].lower() not in ADMIN_EMAILS:
            raise HTTPException(403, "只能删除自己的音乐盒")
        c.execute("DELETE FROM kits WHERE id=?", (kit_id,))
    return {"ok": True}


