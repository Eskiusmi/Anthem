@app.post("/api/auth/register")
def register(body: RegisterIn, request: Request):
    email = body.email.strip().lower()
    name = body.name.strip()
    if not EMAIL_RE.match(email):
        raise HTTPException(400, "邮箱格式不对")
    if not re.match(r"^[\w一-鿿\- ]{2,20}$", name) or name != " ".join(name.split()):
        raise HTTPException(400, "昵称 2–20 个字,只能用中英文、数字、下划线、短横线和空格")
    if not limiter.check("reg:" + client_ip(request), 5, 3600):
        raise HTTPException(429, "注册太频繁,请一小时后再试")
    salt = secrets.token_bytes(16)
    with db() as c:
        if c.execute("SELECT 1 FROM users WHERE email=?", (email,)).fetchone():
            raise HTTPException(409, "这个邮箱已经注册过了,直接登录吧")
        if c.execute("SELECT 1 FROM users WHERE lower(name)=lower(?)", (name,)).fetchone():
            raise HTTPException(409, "这个昵称已经有人用了")
        try:
            uid = c.insert("INSERT INTO users(email, name, pw_salt, pw_hash, created) VALUES(?,?,?,?,?)",
                           (email, name, salt, _hash_pw(body.password, salt), time.time()))
        except IntegrityError:
            raise HTTPException(409, "这个邮箱或昵称刚刚被别人注册了,换一个试试") from None
        tok = _new_session(c, uid)
        row = c.execute("SELECT * FROM users WHERE id=?", (uid,)).fetchone()
    return {"token": tok, "user": public_user(row)}


@app.post("/api/auth/login")
def login(body: LoginIn, request: Request):
    email = body.email.strip().lower()
    ip = client_ip(request)
    if not limiter.check("loginfail-ip:" + ip, 30, 900, record=False) or \
            not limiter.check("loginfail-email:" + email, 10, 900, record=False):
        raise HTTPException(429, "登录失败次数太多,请 15 分钟后再试")
    with db() as c:
        row = c.execute("SELECT * FROM users WHERE email=?", (email,)).fetchone()
        ok = row is not None and hmac.compare_digest(_hash_pw(body.password, row["pw_salt"]), row["pw_hash"])
        if not ok:
            limiter.add("loginfail-ip:" + ip)
            limiter.add("loginfail-email:" + email)
            raise HTTPException(401, "邮箱或密码不对")
        tok = _new_session(c, row["id"])
    return {"token": tok, "user": public_user(row)}


