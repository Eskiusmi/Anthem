@app.post("/api/auth/password")
def change_password(body: PasswordIn, authorization: Optional[str] = Header(default=None), user=Depends(current_user)):
    if not hmac.compare_digest(_hash_pw(body.old_password, user["pw_salt"]), user["pw_hash"]):
        raise HTTPException(401, "原密码不对")
    salt = secrets.token_bytes(16)
    with db() as c:
        c.execute("UPDATE users SET pw_salt=?, pw_hash=? WHERE id=?", (salt, _hash_pw(body.new_password, salt), user["id"]))
        # 其他设备上的登录全部失效,当前这个保留
        c.execute("DELETE FROM sessions WHERE user_id=? AND token_hash<>?", (user["id"], _token_hash(authorization[7:].strip())))
    return {"ok": True}


